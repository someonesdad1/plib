    def Usage(status=1):
        print(wrap.dedent(f'''
        Usage:  {sys.argv[0]} [options] regex1 [regex2...]
          Search for areacodes with a regular expression (expressions are
          OR'd together).  All North American codes from 200-999 are present.
          Dates are year of assignment or the in-service date.  Data from 
          wikipedia 2 Apr 2026.
        Examples:
            '234' will show the area code is from Ohio.
            '.66' will show area codes with 66 in them.
            '-l Calif' shows columnized listing with California area codes highlighted
        Options:
            -a      Show all area code data
            -i      Do not ignore case
            -l      Show overall listing (will colorize regex finds too)
            -m      Show missing codes
        '''))
        exit(status)
    def ParseCommandLine(d):
        d["-a"] = False  # Show all area codes
        d["-i"] = True   # Ignore case
        d["-l"] = False  # Show overall listing
        d["-m"] = False  # Show missing codes
        if len(sys.argv) < 2:
            Usage()
        try:
            opts, args = getopt.getopt(sys.argv[1:], "ailm")
        except getopt.GetoptError as e:
            print(str(e))
            exit(1)
        for o, a in opts:
            if o[1] in list("ailm"):
                d[o] = not d[o]
        return args
